export type Translations = typeof DEFAULT_TRANSLATIONS;

export function useTranslations() {
  const [translations, setTranslations] = useState<Translations>(DEFAULT_TRANSLATIONS);
  const [loading, setLoading] = useState(true);
  const [user, setUser] = useState<User | null>(null);

  useEffect(() => {
    const unsubscribeAuth = onAuthStateChanged(auth, (u) => {
      setUser(u);
    });

    const unsubscribeDB = onSnapshot(
      doc(db, 'translations', 'main'),
      (docSnap) => {
        if (docSnap.exists()) {
          const dbData = docSnap.data();
          const merged = { ...DEFAULT_TRANSLATIONS };
          
          // Deep merge for each language to ensure new keys in DEFAULT_TRANSLATIONS
          // aren't wiped out by an older database document
          for (const lang of Object.keys(DEFAULT_TRANSLATIONS) as (keyof Translations)[]) {
            const defaults = DEFAULT_TRANSLATIONS[lang];
            const stored = (dbData[lang] || {}) as Record<string, string>;
            const langMerged: Record<string, string> = { ...defaults };

            for (const key of Object.keys(defaults)) {
              if (stored[key] !== undefined && stored[key] !== null) {
                // If stored is identical to the English default on a non-English language,
                // and the current default has a localized translation, prefer the translated default
                const isEnglishPlaceholder = 
                  lang !== 'en' && 
                  !key.endsWith('Link') && 
                  stored[key] === DEFAULT_TRANSLATIONS.en[key as keyof typeof DEFAULT_TRANSLATIONS.en] && 
                  defaults[key as keyof typeof defaults] !== DEFAULT_TRANSLATIONS.en[key as keyof typeof DEFAULT_TRANSLATIONS.en];
                
                if (!isEnglishPlaceholder) {
                  langMerged[key] = stored[key];
                }
              }
            }

            merged[lang] = langMerged as typeof defaults;
          }
          
          setTranslations(merged);
        } else {
          // If the document doesn't exist yet, we still return the default
          // The admin can save to create it later
        }
        setLoading(false);
      },
      (error) => {
        // If they lack permissions (e.g. read not allowed), we still show defaults.
        // Wait, we allowed read for anyone!
        console.warn("Translation sync error:", error);
        setLoading(false);
      }
    );

    return () => {
      unsubscribeAuth();
      unsubscribeDB();
    };
  }, []);

  const login = async () => {
    const provider = new GoogleAuthProvider();
    await signInWithPopup(auth, provider);
  };

  const logout = async () => {
    await signOut(auth);
  };

  const saveTranslations = async (newTranslations: Translations) => {
    try {
      await setDoc(doc(db, 'translations', 'main'), newTranslations);
    } catch (error) {
      handleFirestoreError(error, OperationType.WRITE, 'translations/main');
    }
  };

  return { translations, loading, user, login, logout, saveTranslations };
}
